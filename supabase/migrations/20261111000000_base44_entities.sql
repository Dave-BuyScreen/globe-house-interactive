-- RLS, policies and meta trigger for every Base44 table
do $$
declare r record; own text;
begin
  for r in select * from (values ('carousel_image','public',false,false),
    ('channel_content_library','public',false,false),
    ('creator','public',false,false),
    ('episode','public',false,false),
    ('episode_collaborator','public',false,false),
    ('founders_certificate','public',false,false),
    ('live_channel','public',false,false),
    ('live_channel_schedule','public',false,false),
    ('merchant','public',false,false),
    ('notification','private',true,false),
    ('order','private',true,false),
    ('platform_settings','public',false,false),
    ('portal_analytics','public',false,true),
    ('product','public',false,false),
    ('product_registry','public',false,false),
    ('saved_episode','private',true,false),
    ('site_settings','public',false,false),
    ('transaction','private',false,false),
    ('trigger_approval','public',false,false),
    ('trigger_comment','public',false,false),
    ('video_object_mapping','public',false,false),
    ('video_processing_job','private',false,false),
    ('wishlist_item','private',true,false)) as t(tbl, kind, has_user_email, anon_insert) loop
    execute format('alter table public.%I enable row level security', r.tbl);
    execute format('drop trigger if exists set_meta on public.%I', r.tbl);
    execute format('create trigger set_meta before insert or update on public.%I for each row execute function public.gh_set_meta()', r.tbl);
    own := 'public.gh_is_staff() or created_by_id = auth.uid()';
    if r.has_user_email then own := own || $q$ or user_email = (auth.jwt()->>'email')$q$; end if;
    execute format('drop policy if exists %I on public.%I', r.tbl || ' read', r.tbl);
    execute format('create policy %I on public.%I for select using (%s)', r.tbl || ' read', r.tbl,
      case when r.kind = 'private' then own else 'true' end);
    execute format('drop policy if exists %I on public.%I', r.tbl || ' insert', r.tbl);
    execute format('create policy %I on public.%I for insert with check (%s)', r.tbl || ' insert', r.tbl,
      case when r.anon_insert then 'true' else 'auth.uid() is not null' end);
    execute format('drop policy if exists %I on public.%I', r.tbl || ' update', r.tbl);
    execute format('create policy %I on public.%I for update using (public.gh_is_staff() or created_by_id = auth.uid())', r.tbl || ' update', r.tbl);
    execute format('drop policy if exists %I on public.%I', r.tbl || ' delete', r.tbl);
    execute format('create policy %I on public.%I for delete using (public.gh_is_staff() or created_by_id = auth.uid())', r.tbl || ' delete', r.tbl);
  end loop;
end $$;