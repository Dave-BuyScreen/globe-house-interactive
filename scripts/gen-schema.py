"""Generate Supabase SQL from Base44 entity schemas (base44-reference/entities/*.jsonc)."""
import json, glob, re, sys

def snake(n): return re.sub(r'(?<!^)(?=[A-Z])', '_', n).lower()

def coltype(p):
    t = p.get('type')
    if t in ('array', 'object'): return 'jsonb'
    if t == 'number': return 'double precision'
    if t == 'integer': return 'integer'
    if t == 'boolean': return 'boolean'
    return 'text'

def lit(v, typ):
    if v is None: return None
    if typ == 'jsonb': return "'" + json.dumps(v).replace("'", "''") + "'::jsonb"
    if typ == 'boolean': return 'true' if v else 'false'
    if typ in ('double precision', 'integer'): return str(v)
    return "'" + str(v).replace("'", "''") + "'"

# Tables anonymous visitors may insert into (event logging)
ANON_INSERT = {'PortalAnalytics'}
# Tables only the owner / addressee / staff may read
PRIVATE = {'Order', 'Transaction', 'Notification', 'WishlistItem', 'SavedEpisode', 'VideoProcessingJob'}
out = ["-- Generated by scripts/gen-schema.py from Base44 entity schemas. Do not edit by hand.",
       "create extension if not exists pgcrypto;", ""]
mapping = {}
policy_rows = []
for f in sorted(glob.glob('base44-reference/entities/*.jsonc')):
    e = json.load(open(f)); name = e['name']
    if name == 'User': continue
    tbl = snake(name); mapping[name] = tbl
    cols = ["  id text primary key default replace(gen_random_uuid()::text, '-', '')",
            "  created_date timestamptz not null default now()",
            "  updated_date timestamptz not null default now()",
            "  created_by text",
            "  created_by_id uuid"]
    for k, p in e['properties'].items():
        if k in ('id', 'created_date', 'updated_date', 'created_by'): continue
        typ = coltype(p); d = lit(p.get('default'), typ)
        cols.append(f'  "{k}" {typ}' + (f' default {d}' if d else ''))
    out.append(f'create table if not exists public."{tbl}" (\n' + ',\n'.join(cols) + '\n);')
    kind = 'private' if name in PRIVATE else 'public'
    own_email = 'user_email' in e['properties']
    anon = name in ANON_INSERT
    policy_rows.append(f"('{tbl}','{kind}',{str(own_email).lower()},{str(anon).lower()})")
    out.append('')

out.append('''-- RLS, policies and meta trigger for every Base44 table
do $$
declare r record; own text;
begin
  for r in select * from (values ''' + ',\n    '.join(policy_rows) + ''') as t(tbl, kind, has_user_email, anon_insert) loop
    execute format('alter table public.%I enable row level security', r.tbl);
    execute format('drop trigger if exists set_meta on public.%I', r.tbl);
    execute format('create trigger set_meta before insert or update on public.%I for each row execute function public.gh_set_meta()', r.tbl);
    own := 'public.gh_is_staff() or created_by_id = auth.uid()';
    if r.has_user_email then own := own || $q$ or user_email = (auth.jwt()->>'email')$q$; end if;
    execute format('drop policy if exists %I on public.%I', r.tbl || ' read', r.tbl);
    execute format('create policy %I on public.%I for select using (%s)', r.tbl || ' read', r.tbl,
      case when r.kind = 'private' then own else 'true' end);
    execute format('drop policy if exists %I on public.%I', r.tbl || ' insert', r.tbl);
    execute format('create policy %I on public.%I for insert with check (%s)', r.tbl || ' insert', r.tbl,
      case when r.anon_insert then 'true' else 'auth.uid() is not null' end);
    execute format('drop policy if exists %I on public.%I', r.tbl || ' update', r.tbl);
    execute format('create policy %I on public.%I for update using (public.gh_is_staff() or created_by_id = auth.uid())', r.tbl || ' update', r.tbl);
    execute format('drop policy if exists %I on public.%I', r.tbl || ' delete', r.tbl);
    execute format('create policy %I on public.%I for delete using (public.gh_is_staff() or created_by_id = auth.uid())', r.tbl || ' delete', r.tbl);
  end loop;
end $$;''')
header = open('scripts/schema-header.sql').read()
open('supabase/migrations/20261111000000_base44_entities.sql', 'w').write(header + '\n' + '\n'.join(out))
json.dump(mapping, open('src/api/entity-tables.json', 'w'), indent=1)
print(len(mapping), 'tables')
